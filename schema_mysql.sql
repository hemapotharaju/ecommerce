-- ShopEase MySQL schema (used when USE_MYSQL=1)
CREATE TABLE IF NOT EXISTS users(
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL, email VARCHAR(120) UNIQUE NOT NULL,
  password_hash VARCHAR(255) NOT NULL, is_admin TINYINT DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS products(
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(150) NOT NULL, description TEXT,
  price DECIMAL(10,2) NOT NULL, mrp DECIMAL(10,2) DEFAULT 0,
  category VARCHAR(50) DEFAULT 'Electronics',
  image_url TEXT, stock INT DEFAULT 50,
  rating DECIMAL(2,1) DEFAULT 4.0, is_offer TINYINT DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS cart_items(
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL, product_id INT NOT NULL, qty INT DEFAULT 1);
CREATE TABLE IF NOT EXISTS orders(
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL, total DECIMAL(10,2) DEFAULT 0,
  status VARCHAR(30) DEFAULT 'Placed', payment_method VARCHAR(50) DEFAULT 'Cash on Delivery',
  name VARCHAR(100) DEFAULT '', address TEXT, phone VARCHAR(20) DEFAULT '',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS order_items(
  id INT AUTO_INCREMENT PRIMARY KEY,
  order_id INT NOT NULL, product_id INT NOT NULL,
  qty INT NOT NULL, price DECIMAL(10,2) NOT NULL);
